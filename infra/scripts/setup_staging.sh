# Function to create staging backup script
create_staging_backup_script() {
    print_status "Creating staging backup script..."
    
    cat > staging/backup.sh << 'EOF'
#!/bin/bash

# Staging Backup Script

set -e

BACKUP_DIR="staging/backups"
DATE=$(date +%Y%m%d_%H%M%S)
BACKUP_NAME="staging_backup_$DATE"

echo "💾 Creating staging backup: $BACKUP_NAME"

# Create backup directory
mkdir -p "$BACKUP_DIR"

# Backup database
echo "Backing up database..."
docker-compose -f docker-compose.staging.yml exec -T staging-db pg_dump -U schlep_staging igris_overture_staging > "$BACKUP_DIR/${BACKUP_NAME}_database.sql"

# Backup Redis data (if needed)
echo "Backing up Redis data..."
docker-compose -f docker-compose.staging.yml exec -T staging-redis redis-cli --rdb /data/dump.rdb
docker cp $(docker-compose -f docker-compose.staging.yml ps -q staging-redis):/data/dump.rdb "$BACKUP_DIR/${BACKUP_NAME}_redis.rdb"

# Backup logs
echo "Backing up logs..."
docker-compose -f docker-compose.staging.yml exec -T staging-backend tar -czf /tmp/logs.tar.gz /var/log/igris-inertial/
docker cp $(docker-compose -f docker-compose.staging.yml ps -q staging-backend):/tmp/logs.tar.gz "$BACKUP_DIR/${BACKUP_NAME}_logs.tar.gz"

# Create backup archive
echo "Creating backup archive..."
cd "$BACKUP_DIR"
tar -czf "${BACKUP_NAME}.tar.gz" "${BACKUP_NAME}_database.sql" "${BACKUP_NAME}_redis.rdb" "${BACKUP_NAME}_logs.tar.gz"
rm "${BACKUP_NAME}_database.sql" "${BACKUP_NAME}_redis.rdb" "${BACKUP_NAME}_logs.tar.gz"

echo "✅ Backup completed: $BACKUP_DIR/${BACKUP_NAME}.tar.gz"
EOF
    
    chmod +x staging/backup.sh
    print_success "Staging backup script created: staging/backup.sh"
}

# Function to create staging restore script
create_staging_restore_script() {
    print_status "Creating staging restore script..."
    
    cat > staging/restore.sh << 'EOF'
#!/bin/bash

# Staging Restore Script

set -e

if [ $# -eq 0 ]; then
    echo "Usage: $0 <backup_file>"
    echo "Example: $0 staging/backups/staging_backup_20240115_143022.tar.gz"
    exit 1
fi

BACKUP_FILE="$1"
BACKUP_DIR="staging/backups"
RESTORE_DIR="$BACKUP_DIR/restore_$(date +%Y%m%d_%H%M%S)"

echo "🔄 Restoring staging environment from: $BACKUP_FILE"

# Check if backup file exists
if [ ! -f "$BACKUP_FILE" ]; then
    echo "Error: Backup file not found: $BACKUP_FILE"
    exit 1
fi

# Create restore directory
mkdir -p "$RESTORE_DIR"
cd "$RESTORE_DIR"

# Extract backup
echo "Extracting backup..."
tar -xzf "../../$BACKUP_FILE"

# Stop services
echo "Stopping services..."
docker-compose -f ../../docker-compose.staging.yml down

# Restore database
echo "Restoring database..."
docker-compose -f ../../docker-compose.staging.yml up -d staging-db
sleep 10
docker-compose -f ../../docker-compose.staging.yml exec -T staging-db psql -U schlep_staging -d postgres -c "DROP DATABASE IF EXISTS igris_overture_staging;"
docker-compose -f ../../docker-compose.staging.yml exec -T staging-db psql -U schlep_staging -d postgres -c "CREATE DATABASE igris_overture_staging;"
docker-compose -f ../../docker-compose.staging.yml exec -T staging-db psql -U schlep_staging -d igris_overture_staging < *_database.sql

# Restore Redis (if needed)
echo "Restoring Redis data..."
docker-compose -f ../../docker-compose.staging.yml up -d staging-redis
sleep 5
docker cp *_redis.rdb $(docker-compose -f ../../docker-compose.staging.yml ps -q staging-redis):/data/dump.rdb
docker-compose -f ../../docker-compose.staging.yml exec -T staging-redis redis-cli BGREWRITEAOF

# Start all services
echo "Starting all services..."
docker-compose -f ../../docker-compose.staging.yml up -d

# Wait for services to be ready
echo "Waiting for services to be ready..."
sleep 30

# Health check
echo "Performing health check..."
if curl -f http://localhost:8001/api/v1/health/simple >/dev/null 2>&1; then
    echo "✅ Restore completed successfully!"
else
    echo "❌ Health check failed after restore"
    exit 1
fi

# Cleanup
cd ../..
rm -rf "$RESTORE_DIR"

echo "🔄 Restore completed successfully!"
EOF
    
    chmod +x staging/restore.sh
    print_success "Staging restore script created: staging/restore.sh"
}

